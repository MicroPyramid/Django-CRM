"""Render every route in the OpenAPI schema to docs/api/endpoint-index.md.

The curated API pages are written by hand. This index is not: a hand-maintained
list of 350 operations would be wrong within a week. Re-run this script when
routes change:

    cd backend && uv run python scripts/generate_endpoint_index.py
"""

import os
import sys
from pathlib import Path

import django

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "crm.settings")
os.environ.setdefault("SECRET_KEY", "generate-endpoint-index-only")
os.environ.setdefault("ADMIN_EMAIL", "admin@localhost")
django.setup()

from drf_spectacular.generators import SchemaGenerator  # noqa: E402

OUTPUT = (
    Path(__file__).resolve().parent.parent.parent / "docs" / "api" / "endpoint-index.md"
)
METHODS = ("get", "post", "put", "patch", "delete")

HEADER = """# Endpoint index

Every route the API exposes, generated from the OpenAPI schema. The curated
pages in this section explain the endpoints you are most likely to need; this
table exists so nothing is invisible.

Interactive versions of the same schema are served by a running backend at
`/swagger-ui/` and `/api/schema/redoc/`, with the raw document at `/schema/`.

!!! note
    This page is generated by `backend/scripts/generate_endpoint_index.py`.
    Edit that script, not this file.

| Path | Methods |
| --- | --- |
"""


def main() -> None:
    schema = SchemaGenerator().get_schema(request=None, public=True)
    rows = []
    for path in sorted(schema["paths"]):
        methods = sorted(m.upper() for m in schema["paths"][path] if m in METHODS)
        if methods:
            rows.append(f"| `{path}` | {', '.join(methods)} |")
    OUTPUT.write_text(HEADER + "\n".join(rows) + "\n")
    print(f"wrote {OUTPUT}, {len(rows)} paths")


if __name__ == "__main__":
    main()
